#!/usr/bin/env python3
"""Integration test for Ableton Live Set (.als) export round-trip.

Validates that the XML generated by the TypeScript export library can be
gzipped to .als format, decompressed, and contains the expected structural
elements. Uses string/regex checks for colon-based tags (Ableton format)
and ElementTree for well-formedness of non-colon sections.

Usage:
    uv run python scripts/test-als-export.py
"""
