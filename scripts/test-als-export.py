def assert_contains(text: str, pattern: str, msg: str = ""):
    if pattern not in text:
        print(f"  ✗ Expected to find: {pattern}")
        print(f"    {msg}")
        return False
    print(f"  ✓ {pattern}")
    return True


def assert_regex(text: str, pattern: str, msg: str = ""):
    if not re.search(pattern, text):
        print(f"  ✗ Regex not matched: {pattern}")
        print(f"    {msg}")
        return False
    print(f"  ✓ {pattern}")
    return True


def test_gzip_roundtrip():
    raw = SAMPLE_XML.encode("utf-8")
    compressed = gzip.compress(raw)
    assert len(compressed) > 0
    assert len(compressed) < len(raw)
    decompressed = gzip.decompress(compressed).decode("utf-8")
    assert decompressed == SAMPLE_XML
    print(f"  ✓ gzip round-trip: {len(raw)}B -> {len(compressed)}B")


def test_root_element():
    assert_contains(SAMPLE_XML, '<?xml version="1.0" encoding="UTF-8"?>')
    assert_regex(SAMPLE_XML, r'<Ableton\s+MajorVersion="5"\s+MinorVersion="12.0_12117"')


def test_live_set():
    assert_contains(SAMPLE_XML, "<LiveSet>")
    assert_contains(SAMPLE_XML, "</LiveSet>")


def test_master_track():
    assert_contains(SAMPLE_XML, "<MasterTrack>")
    assert_contains(SAMPLE_XML, "<Name Value=\"Master\" />")
    assert_regex(SAMPLE_XML, r'<Manual Value="0\.800000"')


def test_track_structure():
    assert_regex(SAMPLE_XML, r"<MidiTrack>")
    assert_regex(SAMPLE_XML, r"<ClipSlotList>")
    assert_regex(SAMPLE_XML, r"<ClipSlot::Clip Time=")
    assert_regex(SAMPLE_XML, r"<ClipSlot::Clip::ClipTimeable>")
    assert_regex(SAMPLE_XML, r"<ClipSlot::Clip::MidiClip>")
    assert_regex(SAMPLE_XML, r"<SampleType Value=")
    assert_regex(SAMPLE_XML, r"<DeviceChain>")
    assert_regex(SAMPLE_XML, r"<Mixer>")


def test_mixer_section():
    assert_regex(SAMPLE_XML, r'<Manual Value="0.750000"')
    assert_regex(SAMPLE_XML, r'<Manual Value="-0.250000"')
    assert_regex(SAMPLE_XML, r'<Mute Value="false"')


def test_tempo():
    assert_regex(SAMPLE_XML, r'<Tempo>')
    assert_regex(SAMPLE_XML, r'<Manual Value="140.000000"')
    assert_regex(SAMPLE_XML, r'<AutomationTarget Id="0"')


def test_signature():
    assert_regex(SAMPLE_XML, r'<Signature>')
    assert_regex(SAMPLE_XML, r'<Numerator Value="4"')
    assert_regex(SAMPLE_XML, r'<Denominator Value="4"')


def test_write_and_read(tmp_path_str: str):
    als_path = Path(tmp_path_str) / "test_session.als"
    compressed = gzip.compress(SAMPLE_XML.encode("utf-8"))
    als_path.write_bytes(compressed)
    assert als_path.exists()
    assert als_path.stat().st_size > 0
    assert als_path.suffix == ".als"
    raw = gzip.decompress(als_path.read_bytes()).decode("utf-8")
    assert raw == SAMPLE_XML
    size_kb = als_path.stat().st_size / 1024
    print(f"  ✓ Written .als and read back: {size_kb:.1f} KB")


