def main():
    import tempfile
    results = []
    passed = 0
    failed = 0

    print("\n=== .als Export Integration Tests ===\n")

    tests = [
        ("gzip round-trip", test_gzip_roundtrip),
        ("root element", test_root_element),
        ("LiveSet wrapper", test_live_set),
        ("master track", test_master_track),
        ("track structure", test_track_structure),
        ("mixer section", test_mixer_section),
        ("tempo", test_tempo),
        ("signature", test_signature),
        ("write and read .als", lambda: test_write_and_read(tempfile.mkdtemp())),
        ("audio clip structure", test_audio_clip),
        ("MIDI clip KeyTrack", test_midi_clip),
        ("automation envelopes", test_automation),
        ("effects chain", test_effects),
    ]

    for name, fn in tests:
        try:
            fn()
            results.append(("PASS", name))
            passed += 1
        except Exception as e:
            results.append(("FAIL", name, str(e)))
            failed += 1

    print("\n─── Results ───")
    for r in results:
        status = r[0]
        name = r[1]
        if status == "PASS":
            print(f"  ✅ {name}")
        else:
            print(f"  ❌ {name}: {r[2]}")

    print(f"\n{passed}/{passed + failed} passed\n")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    import sys
    sys.exit(main())
